from dataclasses import dataclass
from pathlib import Path
from typing import Any

from evaluation.dataset import EvaluationDataset
from src.inference import ImageCaptioningInference

@dataclass(frozen=True)
class QualitativeSample:
    """
    Represent one quatative image captioning evaluate sample.

    Attributes:
        image_id:
            COCO image identifier

        image_path:
            Path to the evaluated image

        predicted_caption:
            Caption generated by the model

        reference_captions:
            Ground-truth captions associated with the image
    """

    image_id: int
    image_path: Path
    predicted_caption: str
    reference_captions: tuple[str, ...]

def generate_qualitative_samples(
    inference: ImageCaptioningInference,
    dataset: EvaluationDataset,
    num_samples: int,
) -> list[QualitativeSample]:
    """
    Generate qualitative evaluation samples using 
    the production image-captioning inference pipeline.

    Args:
        inference:
            Initialized production inference pipeline.
        
        dataset:
            COCO evaluation dataset
        
        num_samples:
            Number of images to evaluate.

    Returns:
        List of qualitative evaluation records.

    Raises:
        ValueError:
            If num_samples is invalid or image ID is missing.
    """

    # Validate the requested number of samples
    if num_samples <= 0:
        raise ValueError(
            "num_samples must be greater than zero."
        )
    
    if num_samples > len(dataset):
        raise ValueError(
            f"Requested {num_samples} samples, "
            f"but dataset only contains {len(dataset)}"
        )
    
    qualitative_samples: list[QualitativeSample] = []

    # Select a deterministic subset of evaluation images

    for index in range(num_samples):

        sample = dataset[index]

        # A qualitative record requires a COCO image ID
        if sample.image_id is None:
            raise ValueError(
                f"Missing image_id for evaluation sample {index}"
            )
    
        # Generate the caption using production inference
        predicted_caption = inference.predict(
            sample.image_path
        )

        # Construct an immutable qualitative record
        qualitative_sample = QualitativeSample(
            image_id=sample.image_id,
            image_path=sample.image_path,
            predicted_caption=predicted_caption,
            reference_captions=tuple(sample.references),
        )

        qualitative_samples.append(qualitative_sample)

    return qualitative_samples

def serialize_qualitative_samples(
    samples: list[QualitativeSample],
) -> dict[str, Any]:
    """
    Convert qualitative evaluation records into
    a JSON-serializable dictionary.

    Args:
        samples:
            List of qualitative evaluation records.

    Returns:
        Dictionary containing the sample count
        and serialized evaluation samples.
    """
    serialized_samples = []

    for sample in samples:

        serialized_samples.append({
            "image_id": sample.image_id,
            "image_path": str(sample.image_path),
            "predicted_caption": sample.predicted_caption,
            "reference_captions": list(sample.reference_captions),
        })
    
    return {
        "num_samples": len(samples),
        "samples": serialized_samples,
    }